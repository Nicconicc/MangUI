local INTERVAL=10
local DURATION=2.8/.75
local INTENSITY=.75
local C=M.Compat
local groups={
    wa70b7aa5607=true,waf0a666c0b7=true,wabc757f81ee=true,
    centerFire=true,waf465575a72=true,wae608adf3d8=true,
