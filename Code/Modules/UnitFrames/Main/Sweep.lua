local function GroupID(node,index)
    local depth=0
    while node and depth<100 do
        if groups[node.id] then return node.id end
        -- Other independently selectable main-frame groups keep their own art.
        if node.treeParent=="mainComposite" then return end
        node=index[node.parent];depth=depth+1
    end
end

local function Surface(o)
    local n=o.spec
    if n.kind=="portrait" and o.portrait3D and o.portraitModel and not o.portraitModel.portraitFallback then
        return o.frame,o.portraitModel,.105,2
    end
    if n.kind=="bar" and o.clip and o.fill and not n.vertical then
        if o.bar:IsShown() then return o.nativeArtFrame or o.bar,o.nativeArt or o.bar:GetStatusBarTexture(),.105,2 end
        return o.clip,o.fill,.105,2
    end
    if not o.texture or (n.kind~="texture" and n.kind~="sprite" and n.kind~="portrait") then return end
    -- Shadows, dark backing and existing light/particle effects are not reflective surfaces.
    local file=type(n.file)=="string" and n.file:lower() or ""
    -- Additive flame atlases hide their opaque black background through blending.
    -- That background becomes a solid rectangle when reused as an alpha mask.
    -- Keep emissive animation independent of the reflected light band.
    if n.kind=="sprite" and n.blend=="ADD" then return end
    if n.particleFlow or n.spinPeriod or file:find("shadow",1,true)
        or file:find("black",1,true) or file:find("ramp",1,true)
        or file:match("bg$") then return end
    local face=n.kind=="portrait" or file:find("glass",1,true) or n.kind=="sprite"
    return o.frame,o.texture,face and .105 or .42,face and 2 or 1
end

local function Hide(effect)
    if effect.frame:IsShown() then effect.frame:Hide() end
end

local function CopyCoords(effect,...)
    -- Native fill coordinates may be secret. The engine accepts them directly;
    -- Lua must not compare them with the previous coordinates in our cache.
    for i=1,select("#",...) do
        if not C.Readable(select(i,...)) then
            effect.mask:SetTexCoord(...);effect.maskCoords=nil;return
        end
    end
    local a,b,c,d,e,f,g,h=...
    local last=effect.maskCoords
    if not last or last[1]~=a or last[2]~=b or last[3]~=c or last[4]~=d
        or last[5]~=e or last[6]~=f or last[7]~=g or last[8]~=h then
        effect.mask:SetTexCoord(...)
        last=last or {};effect.maskCoords=last
        last[1],last[2],last[3],last[4],last[5],last[6],last[7],last[8]=a,b,c,d,e,f,g,h
    end
end

local function MaskCoords(effect)
    local o,n=effect.object,effect.object.spec
    if n.kind=="portrait" then
        if effect.coordsDirty then effect.mask:SetTexCoord(0,1,0,1);effect.coordsDirty=nil end
        return
    end
    if not effect.coordsDirty and n.kind~="sprite" and not effect.liveCoords then return end
    if not effect.coordsDirty and n.kind=="sprite" and effect.spriteIndex==o.spriteIndex then return end
    local source=effect.maskSource
    if source.GetTexCoord then
        CopyCoords(effect,source:GetTexCoord())
    end
    effect.coordsDirty=nil;effect.spriteIndex=o.spriteIndex
end

local function MaskFile(effect)
    local n=effect.object.spec
    -- Portraits are generated by the client rather than loaded from an art file.
    local file=n.kind=="portrait" and PORTRAIT_MASK or n.file
    if effect.maskSource==effect.object.nativeMask then file=effect.maskSource:GetTexture() end
    if not C.Readable(file) or file==nil then return false end
    file=M:TexturePath(n,file,"sweepMask")
    if file~=effect.file then
        effect.mask:SetTexture(file,"CLAMPTOBLACKADDITIVE","CLAMPTOBLACKADDITIVE")
        effect.file=file
    end
    return true
end

local function Bind(effect,parent,source,force)
    local o=effect.object
    local native=o.spec.kind=="bar" and source~=o.fill
    local bounds=native and source or parent
    local maskSource=native and o.spec.materialPath and o.nativeMask or source
    local level=o.frame:GetFrameLevel()+1
    if not force and effect.parent==parent and effect.source==source
        and effect.maskSource==maskSource and effect.level==level then return end
    effect.parent,effect.source,effect.maskSource=parent,source,maskSource
    effect.level=level;effect.liveCoords=native
    effect.coordsDirty=true;effect.maskCoords=nil;effect.spriteIndex=nil
    effect.scale=nil;effect.height=nil
    effect.frame:SetParent(parent);effect.frame:SetAllPoints(bounds)
    -- Respect the surface's actual draw order. A high particle/light layer in
    -- the same group must not lift strip reflections above the portrait rim.
    effect.frame:SetFrameLevel(level)
    effect.mask:ClearAllPoints();effect.mask:SetAllPoints(maskSource)
end

function S.Configure(view)
    local main=view.nodes.mainComposite
    local avatar=view.nodes.wabc757f81ee
    if not main or not avatar then
        for _,effect in pairs(view.mainSweep and view.mainSweep.effects or {}) do Hide(effect) end
        if view.mainSweep then view.mainSweep.active={};view.mainSweep.started=nil end
        return
    end
    local sweep=view.mainSweep
    if not sweep then
        local root=CreateFrame("Frame",nil,main.frame)
        root:SetSize(2,2);root:EnableMouse(false)
        sweep={root=root,effects={}};view.mainSweep=sweep
        root:SetScript("OnHide",function()sweep.started=nil end)
    end
    -- mainComposite is a logical group. Anchor its controller to the physical
    -- portrait root so existing whole-frame drag and scale operations carry it.
    sweep.root:SetParent(main.frame)
    local avatarScale=C.Number(avatar.frame:GetEffectiveScale())
    local mainScale=C.Number(main.frame:GetEffectiveScale())
    if not avatarScale or not mainScale or mainScale<=0 then
        for _,effect in pairs(sweep.effects) do Hide(effect) end
        sweep.active={};sweep.root:Hide();return
    end
    sweep.root:SetScale(avatarScale/mainScale)
    sweep.root:ClearAllPoints();sweep.root:SetPoint("CENTER",avatar.frame,"CENTER")
    sweep.root:Show()
    sweep.active={};sweep.clock=nil;sweep.nextBounds=0
    for _,effect in pairs(sweep.effects) do effect.active=false end
    for _,o in ipairs(view.ordered) do
        local id=GroupID(o.spec,view.byID)
        local parent,source,alpha,widthFactor
        if id then parent,source,alpha,widthFactor=Surface(o) end
        if parent and parent.CreateMaskTexture then
            local effect=sweep.effects[o.spec.id]
            if not effect then
                local frame=CreateFrame("Frame",nil,parent)
                frame:EnableMouse(false)
                frame:SetClipsChildren(true)
                local mask=frame:CreateMaskTexture(nil,"OVERLAY")
                local band=frame:CreateTexture(nil,"OVERLAY")
                band:SetTexture(M:TexturePath(o.spec,GRADIENT,"sweepGradient"),"MIRROR","CLAMPTOBLACKADDITIVE")
                band:SetTexCoord(-1,1,0,1);band:SetBlendMode("ADD")
                band:AddMaskTexture(mask)
                effect={frame=frame,mask=mask,band=band};sweep.effects[o.spec.id]=effect
            end
            effect.object=o;effect.widthFactor=widthFactor
            effect.active=true;Bind(effect,parent,source,true)
            effect.band:SetVertexColor(1,.94,.78,alpha*INTENSITY)
            Hide(effect)
            sweep.active[#sweep.active+1]=effect
        end
    end
    for _,effect in pairs(sweep.effects) do if not effect.active then Hide(effect) end end
end

local function Bounds(sweep,now)
    local root=sweep.root
    local rootScale=C.Number(root:GetEffectiveScale())
    local cx,cy=root:GetCenter()
    cx,cy=C.Number(cx),C.Number(cy)
    if not cx or not cy or not rootScale or rootScale<=0 then return false end
    local left,right,bottom,top
    for _,effect in ipairs(sweep.active) do
        -- A native filled texture carries secret dimensions after SetValue.
        -- Use the fixed surface bounds; the existing frame and mask still clip
        -- the reflection to the actual filled silhouette inside the engine.
        local f=effect.parent
        local x,y=f:GetCenter()
        x,y=C.Number(x),C.Number(y)
        local effectiveScale=C.Number(f:GetEffectiveScale())
        local width,height=C.Number(f:GetWidth()),C.Number(f:GetHeight())
        if x and y and effectiveScale and width and height then
            local scale=effectiveScale/rootScale
            local w,h=width*scale/2,height*scale/2
            x,y=x*scale-cx,y*scale-cy
            left=math.min(left or x-w,x-w);right=math.max(right or x+w,x+w)
            bottom=math.min(bottom or y-h,y-h);top=math.max(top or y+h,y+h)
        end
    end
    if not left then return false end
    sweep.height=math.max(80,(top-bottom)*1.5)
    sweep.width=M.Clamp(sweep.height*180/760,45,180)
    sweep.skew=sweep.height*130/760
    sweep.y=(top+bottom)/2
    local margin=sweep.width+sweep.skew
    sweep.left=left-margin;sweep.travel=right-left+2*margin
    sweep.nextBounds=now+.1
    return true
end

local function BandSize(effect,sweep,scale)
    if effect.scale==scale and effect.height==sweep.height and effect.width==sweep.width then return end
    effect.band:SetSize(sweep.width*effect.widthFactor/scale,sweep.height/scale)
    if effect.band.SetVertexOffset then
        local skew=sweep.skew/scale
        effect.band:SetVertexOffset(1,skew,0);effect.band:SetVertexOffset(3,skew,0)
        effect.band:SetVertexOffset(2,-skew,0);effect.band:SetVertexOffset(4,-skew,0)
    end
    effect.scale=scale;effect.height=sweep.height;effect.width=sweep.width
end

function S.Animate(view)
    local sweep=view.mainSweep
    if not sweep or #sweep.active==0 then return end
    local main=view.nodes.mainComposite
    if not view.root:IsVisible() or not main or (not view.preview and main.spec.enabled==false) then
        for _,effect in ipairs(sweep.active) do Hide(effect) end
        sweep.started=nil;return
    end
    local now=GetTime();local clock=math.floor(now*60)
    if sweep.clock==clock then return end
    sweep.clock=clock
    -- Health and portraits may switch their native/static rendering surface.
    -- Reuse the effect while following whichever surface is currently drawn.
    for _,effect in ipairs(sweep.active) do
        if effect.object.spec.kind=="bar" or effect.object.spec.kind=="portrait" then
            local parent,source=Surface(effect.object)
            if parent and source then Bind(effect,parent,source) end
        end
    end
    local visible=false
    for _,effect in ipairs(sweep.active) do
        if effect.object.frame:IsVisible() and effect.source:IsShown() then visible=true;break end
    end
    if not visible then
        for _,effect in ipairs(sweep.active) do Hide(effect) end
        sweep.started=nil;return
    end
    sweep.started=sweep.started or now
    local elapsed=(now-sweep.started)%INTERVAL
    if elapsed>=DURATION then
        for _,effect in ipairs(sweep.active) do Hide(effect) end
        sweep.phase=nil;return
    end
    if (now>=sweep.nextBounds or not sweep.height) and not Bounds(sweep,now) then
        for _,effect in ipairs(sweep.active) do Hide(effect) end
        return
    end
    sweep.phase=elapsed/DURATION
    local x=sweep.left+sweep.travel*sweep.phase
    local rootScale=C.Number(sweep.root:GetEffectiveScale())
    if not rootScale or rootScale<=0 then
        for _,effect in ipairs(sweep.active) do Hide(effect) end
        return
    end
    for _,effect in ipairs(sweep.active) do
        if effect.object.frame:IsVisible() and effect.source:IsShown() and MaskFile(effect) then
            MaskCoords(effect)
            local effectiveScale=C.Number(effect.frame:GetEffectiveScale())
            local scale=effectiveScale and effectiveScale/rootScale
            if scale and scale>0 then
                BandSize(effect,sweep,scale)
                effect.band:ClearAllPoints()
                effect.band:SetPoint("CENTER",sweep.root,"CENTER",x/scale,sweep.y/scale)
                if not effect.frame:IsShown() then effect.frame:Show() end
            else Hide(effect) end
        else Hide(effect) end
    end
end
